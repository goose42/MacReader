// Regenerates MacReaderKit/Sources/MacReaderKit/Structure/CodeLigatureTable.swift from the JetBrains Mono font
// (SIL OFL 1.1, https://github.com/JetBrains/JetBrainsMono). Run via Scripts/generate-ligature-table.sh.
import CoreGraphics
import CoreText
import Foundation

let names: [String: String] = [
    "underscore": "_", "hyphen": "-", "greater": ">", "less": "<", "equal": "=", "slash": "/", "asterisk": "*",
    "period": ".", "colon": ":", "semicolon": ";", "exclam": "!", "question": "?", "ampersand": "&", "bar": "|",
    "plus": "+", "numbersign": "#", "percent": "%", "dollar": "$", "at": "@", "backslash": "\\", "asciitilde": "~",
    "asciicircum": "^", "braceleft": "{", "braceright": "}", "bracketleft": "[", "bracketright": "]",
    "parenleft": "(", "parenright": ")", "quotesingle": "'", "quotedbl": "\"", "w": "w", "x": "x", "F": "F",
]

func text(forGlyphNamed name: String) -> String? {
    guard name.hasSuffix(".liga") else { return nil }
    let parts = name.dropLast(".liga".count).split(separator: "_", omittingEmptySubsequences: false).map(String.init)
    // Names like "underscore_underscore" split on the separator between components, but "asciitilde" etc. contain none.
    let pieces = parts.compactMap { names[$0] }
    return pieces.count == parts.count && pieces.count >= 2 ? pieces.joined() : nil
}

let arguments = CommandLine.arguments
guard arguments.count == 3, let data = FileManager.default.contents(atPath: arguments[1]),
      let font = CGDataProvider(data: data as CFData).flatMap(CGFont.init)
else { fatalError("usage: GenerateLigatureTable <JetBrainsMono-Regular.ttf> <output.swift>") }

let coreText = CTFontCreateWithGraphicsFont(font, 100, nil, nil)
var seen = Set<String>()
var rows: [String] = []
var skipped: [String] = []
for glyph in 0..<font.numberOfGlyphs {
    guard let name = font.name(for: CGGlyph(glyph)) as String?, name.hasSuffix(".liga") else { continue }
    guard let ligature = text(forGlyphNamed: name), let fingerprint = GlyphFingerprint(glyph: CGGlyph(glyph), in: coreText) else {
        skipped.append(name)
        continue
    }
    guard seen.insert(ligature + fingerprint.hex).inserted else { continue }
    let escaped = ligature.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
    rows.append("        (\"\(escaped)\", \"\(fingerprint.hex)\"),")
}

let source = """
// Generated by Scripts/GenerateLigatureTable from JetBrains Mono (SIL OFL 1.1). Do not edit.

/// The ligatures of JetBrains Mono as outline fingerprints, used to read text from PDFs whose embedded code font
/// has no Unicode map.
enum CodeLigatureTable {
    static let entries: [(text: String, fingerprint: String)] = [
\(rows.joined(separator: "\n"))
    ]
}

"""
try source.write(toFile: arguments[2], atomically: true, encoding: .utf8)
print("wrote \(rows.count) ligatures; skipped \(skipped.count): \(skipped.sorted().joined(separator: " "))")
